// Ранги: имя, минимальный счёт, вес (шанс выпадения)
private data class RankDef(val name: String, val minScore: Int, val weight: Int, val pool: List<String>)

private val ranks = listOf(
    RankDef("Обычная", 0, 40, earlyPhrases),
    RankDef("Осмысленная", 50, 26, midPhrases),
    RankDef("Глубокая", 250, 16, veteranPhrases),
    RankDef("Философская", 1000, 10, epicPhrases),
    RankDef("Мудрая", 5000, 6, zenPhrases),
    RankDef("Просветлённая", 10000, 2, enlightenedPhrases)
)

private fun pickFrom(pool: List<String>, last: String?): String {
    val candidates = pool.filter { it != last }
    return (candidates.ifEmpty { pool }).random()
}

/**
 * Возвращает (фраза, ранг).
 * Быстрые серии дают скоростные ранги; иначе ранг выбирается
 * по весу среди рангов, открытых текущим счётом.
 */
fun rollPhrase(score: Int, streak: Int, lastPhrase: String?): Pair<String, String> {
    if (streak >= 15) return pickFrom(ultraFastPhrases, lastPhrase) to "Сверхзвуковая"
    if (streak >= 8) return pickFrom(fastPhrases, lastPhrase) to "Быстрая"
    val unlocked = ranks.filter { score >= it.minScore }
    val total = unlocked.sumOf { it.weight }
    var roll = Random.nextInt(total)
    for (rank in unlocked) {
        roll -= rank.weight
        if (roll < 0) return pickFrom(rank.pool, lastPhrase) to rank.name
    }
    return pickFrom(earlyPhrases, lastPhrase) to "Обычная"
}
